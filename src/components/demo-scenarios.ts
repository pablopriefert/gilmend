// The six demo cases of the video (and a seventh, German one, since 28 Oct 2026), one click each on the "New report" screen. They fill the
// form with a fictitious customer message and a photo. The wording comes from
// data/demo-cases.json (the agent's expected outcomes live there too), so a click here gives the
// agent exactly the case that file describes; src/components/demo-scenarios.test.ts fails if the two drift.
//
// Photos: each scenario points to the demo photo served by /api/demo-photo (data/photos/<name>:
// the photo we shoot ourselves, else the provisional stand-in, see data/photos/README.md) and
// falls back to a flat illustration (public/demo/illustration-*.png, generated by
// scripts/make-demo-photos.mjs) when the server has neither. Dropping the real JPEG into
// data/photos/ is all it takes to switch: no code change. (They used to point to
// /demo/<name>.jpg, a folder that never held them, so the buttons always showed illustrations.)

import type { LanguageCode } from "@/lib/languages";

export interface DemoPhoto {
  /** The demo photo, tried first (served from data/photos by /api/demo-photo). */
  src: string;
  /** Placeholder illustration used when `src` is not there yet. */
  fallback: string;
}

/** How the card colours the expected outcome (always paired with an icon and the words). */
export type OutcomeTone = "success" | "neutral" | "info" | "warning";

export interface DemoScenario {
  id: string;
  /** Card title. */
  title: string;
  /** What the case demonstrates, shown under the title. */
  shows: string;
  /**
   * Presentation only (27 Oct 2026, Gilmend redesign): the carrier of the fictitious order, as
   * data/fixtures/orders.json has it, and the outcome the case is designed to show
   * (data/demo-cases.json `expected`). It is what the case is built to demonstrate, never a
   * promise about a run: the agent still decides for itself.
   */
  carrier: string;
  outcome: { label: string; tone: OutcomeTone };
  orderNumber: string;
  email: string;
  message: string;
  language: LanguageCode;
  photos: DemoPhoto[];
}

